def _sport(
    sport_id: str,
    name: str,
    category: str,
    icon: str,
    *,
    booking: bool,
    queue: bool,
    resources: list[str],
    players: tuple[int, int],
    formats: list[dict],
    match_type: str,
    kinds: list[str],
    scoring: dict,
    queue_modes: tuple[str, ...] = (),
    levels: list[str] | None = None,
    routes: bool = False,
    kind_labels: dict | None = None,
) -> dict:
    return {
        "id": sport_id,
        "name": name,
        "category_id": category,
        "icon": icon,
        "booking_eligible": booking,
        "queue_eligible": queue,
        "resource_types": resources,
        "player_config": {"minPlayers": players[0], "maxPlayers": players[1], "teamFormats": formats},
        "match_format": {
            "type": match_type,
            "sessionKinds": kinds,
            "queueModes": list(queue_modes),
            "skillLevels": levels or GENERAL_LEVELS,
            "usesRoutes": routes,
            "kindLabels": kind_labels or {},
        },
        "scoring_config": scoring,
    }


