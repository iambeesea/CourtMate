GENERAL_LEVELS = ["All levels", "Beginner", "Intermediate", "Advanced"]


def _formats(*items: tuple[str, str, int]) -> list[dict]:
    return [{"id": key, "label": label, "playersPerSide": size} for key, label, size in items]


SINGLES_DOUBLES = _formats(("singles", "Singles", 1), ("doubles", "Doubles", 2), ("mixed_doubles", "Mixed doubles", 2))


def _two_sided(kind: str, unit: str, *, best_of: int | None = None, game_label: str = "", allow_draw: bool = False, player_fields=()):
    return {
        "kind": kind,
        "unit": unit,
        "bestOf": best_of,
        "gameLabel": game_label,
        "allowDraw": allow_draw,
        "playerFields": [{"key": key, "label": label} for key, label in player_fields],
        "activityFields": [],
        "aggregations": [],
    }


def _individual(fields: list[dict], aggregations: list[dict]) -> dict:
    return {
        "kind": "individual",
        "unit": "",
        "bestOf": None,
        "gameLabel": "",
        "allowDraw": False,
        "playerFields": [],
        "activityFields": fields,
        "aggregations": aggregations,
    }


ATTENDANCE_ONLY = {
    "kind": "none",
    "unit": "",
    "bestOf": None,
    "gameLabel": "",
    "allowDraw": False,
    "playerFields": [],
    "activityFields": [],
    "aggregations": [],
}

